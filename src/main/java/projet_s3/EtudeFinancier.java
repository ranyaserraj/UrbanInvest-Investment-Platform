package projet_s3;

public class EtudeFinancier {
	private String nomComplet;
    private String telephone;
    private String nomDuProjet;
    private String typeInvestissement;
    private String villeRegion;
    private String adresseExacte;
    private String superficieEstimee;
    private String budgetEstimee;
    private String sourceFinancement;

    // Getters et setters
    public String getNomComplet() { return nomComplet; }
    public void setNomComplet(String nomComplet) { this.nomComplet = nomComplet; }

    public String getTelephone() { return telephone; }
    public void setTelephone(String telephone) { this.telephone = telephone; }

    public String getNomDuProjet() { return nomDuProjet; }
    public void setNomDuProjet(String nomDuProjet) { this.nomDuProjet = nomDuProjet; }

    public String getTypeInvestissement() { return typeInvestissement; }
    public void setTypeInvestissement(String typeInvestissement) { this.typeInvestissement = typeInvestissement; }

    public String getVilleRegion() { return villeRegion; }
    public void setVilleRegion(String villeRegion) { this.villeRegion = villeRegion; }

    public String getAdresseExacte() { return adresseExacte; }
    public void setAdresseExacte(String adresseExacte) { this.adresseExacte = adresseExacte; }

    public String getSuperficieEstimee() { return superficieEstimee; }
    public void setSuperficieEstimee(String superficieEstimee) { this.superficieEstimee = superficieEstimee; }

    public String getBudgetEstimee() { return budgetEstimee; }
    public void setBudgetEstimee(String budgetEstimee) { this.budgetEstimee = budgetEstimee; }

    public String getSourceFinancement() { return sourceFinancement; }
    public void setSourceFinancement(String sourceFinancement) { this.sourceFinancement = sourceFinancement; }
}

